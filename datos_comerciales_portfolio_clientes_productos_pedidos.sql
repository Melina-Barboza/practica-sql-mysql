CREATE DATABASE IF NOT EXISTS datos_comerciales;

USE datos_comerciales;



CREATE TABLE Clientes (id_cliente INT AUTO_INCREMENT PRIMARY KEY,nombre VARCHAR(100),ciudad VARCHAR(80),edad INT);

CREATE TABLE Productos (id_producto INT AUTO_INCREMENT PRIMARY KEY,nombre_producto VARCHAR(120),categoria VARCHAR(80),precio DECIMAL(10,2));

CREATE TABLE Pedidos (id_pedido INT AUTO_INCREMENT PRIMARY KEY,id_cliente INT,id_producto INT,cantidad INT,fecha DATE,FOREIGN KEY (id_cliente) REFERENCES Clientes(id_cliente),FOREIGN KEY (id_producto) REFERENCES Productos(id_producto));

